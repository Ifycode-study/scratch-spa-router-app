const express = require('express');
const path = require('path');

const app = express();

app.use('/@static', express.static(path.join(__dirname, '../../@node_modules', '/@static')));
app.use('/', express.static(path.join(__dirname, '../../@app_web', '/')));

app.get('/{*path}', (req, res) => {
    res.sendFile(path.join(__dirname, '../../@app_web', 'index.html'));
});

app.listen(process.env.PORT || 5700, () => {
    console.log('Web server running...');
});